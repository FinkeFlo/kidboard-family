import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import type { Plugin } from "vite";

/**
 * HTTP headers for the static assets (T-25). Workers Static Assets reads a `_headers`
 * file from the assets directory (`apps/web/dist`) and applies its rules to every asset
 * response, including the single-page-application fallback. It does not apply to
 * Worker responses: `/api/*` sets its own headers in the Hono app.
 *
 * The file is generated after the build from the final `dist/index.html`, so the CSP
 * hash of the inline theme boot script always matches the shipped bytes. Cache-Control
 * is left alone on purpose: the platform default (`public, max-age=0,
 * must-revalidate` + ETag) is right for `sw.js`, `index.html` and the manifest
 * (docs/DEPLOY.md, ADR-0006).
 */

/** One `_headers` rule: a URL pattern and the headers attached to matching responses. */
export interface HeaderRule {
  readonly pattern: string;
  readonly headers: ReadonlyArray<readonly [name: string, value: string]>;
}

export const HEADERS_FILE_NAME = "_headers";

const SCRIPT_RE = /<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi;
const SRC_ATTR_RE = /(?:^|\s)src\s*=/i;

/**
 * CSP source expressions (`'sha256-…'`) of every inline classic or module script in
 * `html`, in document order. Scripts with a `src` attribute are skipped. Line endings are
 * normalised to LF first, as the HTML parser does before the browser hashes the text.
 */
export function inlineScriptHashes(html: string): string[] {
  const normalized = html.replace(/\r\n?/g, "\n");
  const hashes: string[] = [];
  for (const match of normalized.matchAll(SCRIPT_RE)) {
    const [, attributes = "", body = ""] = match;
    if (SRC_ATTR_RE.test(attributes)) {
      continue;
    }
    const digest = createHash("sha256").update(body, "utf8").digest("base64");
    hashes.push(`'sha256-${digest}'`);
  }
  return hashes;
}

/** Origins allowed to embed the board in a frame (`frame-ancestors`). */
export const FRAME_ANCESTORS: readonly string[] = ["'self'"];

/**
 * Content-Security-Policy of the board: same-origin only, no eval, no inline code except
 * the hashed inline scripts. Only the board itself may frame it (`frame-ancestors`):
 * the parent editor has actions to click-jack. A wall dashboard (e.g. Home Assistant)
 * that embeds the board adds its origin to `FRAME_ANCESTORS` (docs/DEPLOY.md).
 */
export function contentSecurityPolicy(scriptHashes: readonly string[]): string {
  const directives: Array<[string, string[]]> = [
    ["default-src", ["'self'"]],
    ["script-src", ["'self'", ...scriptHashes]],
    ["style-src", ["'self'"]],
    ["img-src", ["'self'"]],
    ["font-src", ["'self'"]],
    ["connect-src", ["'self'"]],
    ["manifest-src", ["'self'"]],
    ["worker-src", ["'self'"]],
    ["object-src", ["'none'"]],
    ["base-uri", ["'none'"]],
    ["form-action", ["'none'"]],
    ["frame-ancestors", [...FRAME_ANCESTORS]],
  ];
  return directives
    .map(([name, sources]) => `${name} ${sources.join(" ")}`)
    .join("; ");
}

/** The rules written to `dist/_headers` for a built `index.html`. */
export function staticHeaderRules(indexHtml: string): HeaderRule[] {
  return [
    {
      pattern: "/*",
      headers: [
        [
          "Content-Security-Policy",
          contentSecurityPolicy(inlineScriptHashes(indexHtml)),
        ],
        ["X-Content-Type-Options", "nosniff"],
        // The first visit carries `?key=<token>`: never send the URL as a referrer.
        ["Referrer-Policy", "no-referrer"],
        [
          "Permissions-Policy",
          "camera=(), microphone=(), geolocation=(), payment=(), usb=()",
        ],
      ],
    },
  ];
}

/** Serialises rules in the `_headers` format (pattern line, indented `Name: value`). */
export function renderHeadersFile(rules: readonly HeaderRule[]): string {
  const blocks = rules.map((rule) =>
    [rule.pattern, ...rule.headers.map(([n, v]) => `  ${n}: ${v}`)].join("\n"),
  );
  return `# Generated by apps/web/headers/staticHeaders.ts during \`vite build\`. Do not edit.\n${blocks.join("\n\n")}\n`;
}

/**
 * Parses the subset of the `_headers` format that {@link renderHeadersFile} writes:
 * `#` comments, unindented pattern lines and indented `Name: value` lines. Throws on
 * anything else, so the preview server never silently drops a rule.
 */
export function parseHeadersFile(text: string): HeaderRule[] {
  const rules: Array<{ pattern: string; headers: Array<[string, string]> }> =
    [];
  for (const [index, line] of text.split(/\r?\n/).entries()) {
    if (line.trim() === "" || line.trimStart().startsWith("#")) {
      continue;
    }
    if (!/^\s/.test(line)) {
      rules.push({ pattern: line.trim(), headers: [] });
      continue;
    }
    const current = rules.at(-1);
    const separator = line.indexOf(":");
    if (current === undefined || separator === -1) {
      throw new Error(
        `_headers line ${String(index + 1)}: expected "Name: value" below a pattern`,
      );
    }
    current.headers.push([
      line.slice(0, separator).trim(),
      line.slice(separator + 1).trim(),
    ]);
  }
  return rules;
}

/**
 * Whether a rule pattern matches a request path. Supports exact paths and one trailing
 * splat (`/*`, `/assets/*`), the forms this project uses.
 */
export function patternMatches(pattern: string, pathname: string): boolean {
  if (pattern.endsWith("*")) {
    return pathname.startsWith(pattern.slice(0, -1));
  }
  return pattern === pathname;
}

/**
 * Vite plugin: writes `dist/_headers` after the bundle is written, and makes `vite
 * preview` (used by the E2E tests) send the same headers, so the suite runs under the
 * production CSP.
 */
export function staticHeadersPlugin(): Plugin {
  let outDir = "";
  return {
    name: "kidboard:static-headers",
    configResolved(config) {
      outDir = resolve(config.root, config.build.outDir);
    },
    writeBundle: {
      order: "post",
      handler() {
        const html = readFileSync(resolve(outDir, "index.html"), "utf8");
        writeFileSync(
          resolve(outDir, HEADERS_FILE_NAME),
          renderHeadersFile(staticHeaderRules(html)),
        );
      },
    },
    configurePreviewServer(server) {
      const rules = parseHeadersFile(
        readFileSync(resolve(outDir, HEADERS_FILE_NAME), "utf8"),
      );
      server.middlewares.use((req, res, next) => {
        const pathname = new URL(req.url ?? "/", "http://preview.invalid")
          .pathname;
        for (const rule of rules) {
          if (patternMatches(rule.pattern, pathname)) {
            for (const [name, value] of rule.headers) {
              res.setHeader(name, value);
            }
          }
        }
        next();
      });
    },
  };
}
